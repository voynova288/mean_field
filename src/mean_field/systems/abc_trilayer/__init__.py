"""ABC-trilayer system adapters.

The Vituri projected vertex is authority-limited: it is derived from the
projected Hamiltonian rather than copied from literal Eq. C3, which is
internally inconsistent with its stated antisymmetry.  The fixed derivation
source is the pinned arXiv-v1 ``SM.tex``; the separate published-PRB evidence
is pinned to PDF SHA256
``2226e17ed95bd867607787b47343fe5fc77f2c30557023e349d86e55159c0765``.
The package does not claim a paper phase gauge or production/paper numerical
parity for that layer.  The local Vituri scalar-Hessian adapter maps the
derived vertex to paper C9.  Its separate signed-q adapter assembles four
independent local A/B lanes into the core typed generic-q classes without
repair, but remains diagnostic-only: diagonal-HF stationarity, real
mesh/area/q0/UV/CDW authority, and production/executable readiness are not
established.  The separate half-metal HF preflight validates provider-owned geometry,
ensemble, SCF, shared-functional, and attested-source receipts.  Its only
positive aggregate result is ``receipt_set_complete``; provider metadata is
``provider_metadata_attested`` while scientific execution remains explicitly
false.  The separate array-only replay adapter can load and verify canonical
saved arrays and base-mesh source structure; SCF trajectory, branch-table,
pocket-refinement, E->F->H functional-chain, and paper-reproduction replay
remain explicit NO-GO boundaries.
"""

